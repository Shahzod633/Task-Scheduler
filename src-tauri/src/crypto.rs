//! Шифрование базы: SQLCipher + ключ в Диспетчере учётных данных Windows.
//!
//! Ключ намеренно не лежит рядом с базой. Файл с ключом в той же папке — это
//! замок, к которому ключ примотан скотчем: любой, кто унёс папку, унёс и то и
//! другое. Диспетчер учётных данных привязывает секрет к учётной записи
//! Windows, поэтому скопированный на флешку файл базы на чужой машине не
//! открывается.
//!
//! **Обратная сторона, о которой нельзя забывать:** потеря учётной записи
//! Windows (переустановка системы, сброс профиля) означает потерю ключа, а
//! значит и базы. Поэтому старый незашифрованный файл при миграции
//! переименовывается в `.bak` и **не удаляется** — решение о его судьбе
//! принимает человек, а не программа.

use rusqlite::{Connection, Result};
use std::path::Path;

/// Имя, под которым секрет виден в Диспетчере учётных данных.
///
/// Меняя эти две строки, вы теряете доступ к уже сохранённому ключу: старая
/// запись останется висеть, а приложение сочтёт, что ключа нет, и создаст
/// новый — которым существующую базу уже не открыть.
const KEYRING_SERVICE: &str = "TaskFlow";
const KEYRING_ENTRY: &str = "database-key";

/// Первые 16 байт незашифрованного файла SQLite. У файла SQLCipher на этом
/// месте лежит случайная соль, так что заголовок — дешёвый и надёжный признак
/// того, что база ещё не зашифрована.
const SQLITE_HEADER: &[u8] = b"SQLite format 3\0";

/// Начало имени, которое получает незашифрованный файл после миграции. К нему
/// дописывается отметка времени.
///
/// Фиксированное имя выглядело бы аккуратнее, но ломало бы восстановление:
/// положив расшифрованный экспорт на место базы, человек получил бы отказ
/// мигрировать («такой .bak уже есть») — то есть приложение, которое не
/// запускается, ровно в тот момент, когда он спасает данные.
pub const BACKUP_PREFIX: &str = ".plaintext-";

/// Ключ в виде 64 шестнадцатеричных символов (32 байта).
///
/// Хранится текстом, потому что Диспетчер учётных данных хранит строки, а
/// шестнадцатеричная запись переживает любое кодирование без потерь — в
/// отличие от сырых байтов, часть которых не образует корректного UTF-16.
#[derive(Clone)]
pub struct DbKey(String);

impl DbKey {
    /// `PRAGMA key` в форме сырого ключа: `x'<hex>'`.
    ///
    /// Сырой ключ, а не парольная фраза — тогда SQLCipher не гоняет PBKDF2 при
    /// каждом открытии базы (256 000 итераций по умолчанию, это заметная пауза
    /// на запуске). Ключ и так случаен на все 256 бит, растягивать нечего.
    fn pragma_literal(&self) -> String {
        format!("x'{}'", self.0)
    }
}

/// Достаёт ключ из Диспетчера учётных данных, а если его там нет — создаёт
/// новый и сохраняет.
///
/// Отсутствие записи — это нормальный первый запуск, а не ошибка. Ошибкой
/// считается только невозможность прочитать или записать сам Диспетчер.
pub fn load_or_create_key() -> std::result::Result<DbKey, String> {
    let entry = keyring::Entry::new(KEYRING_SERVICE, KEYRING_ENTRY)
        .map_err(|e| format!("Диспетчер учётных данных недоступен: {}", e))?;

    match entry.get_password() {
        Ok(hex) if is_valid_hex_key(&hex) => Ok(DbKey(hex)),
        Ok(bad) => Err(format!(
            "Ключ в Диспетчере учётных данных испорчен ({} символов вместо 64). \
             База не открыта намеренно: с неверным ключом SQLCipher создал бы \
             пустую базу поверх существующей.",
            bad.len()
        )),
        Err(keyring::Error::NoEntry) => {
            let key = generate_key()?;
            entry
                .set_password(&key.0)
                .map_err(|e| format!("Не удалось сохранить ключ: {}", e))?;
            log::info!("Создан новый ключ шифрования базы");
            Ok(key)
        }
        Err(e) => Err(format!("Не удалось прочитать ключ: {}", e)),
    }
}

/// 32 случайных байта из системного источника, в шестнадцатеричной записи.
fn generate_key() -> std::result::Result<DbKey, String> {
    let mut bytes = [0u8; 32];
    getrandom::getrandom(&mut bytes)
        .map_err(|e| format!("Системный источник случайности недоступен: {}", e))?;
    Ok(DbKey(bytes.iter().map(|b| format!("{:02x}", b)).collect()))
}

/// 64 символа из `0-9a-f` — ровно то, что пишет `generate_key`.
///
/// Проверка нужна не из вежливости: значение подставляется в текст SQL
/// (`PRAGMA key = x'…'`), потому что связанный параметр SQLCipher принял бы за
/// парольную фразу, а не за сырой ключ. Значит, содержимое обязано быть
/// заведомо безопасным.
fn is_valid_hex_key(s: &str) -> bool {
    s.len() == 64 && s.bytes().all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

/// Открывает зашифрованную базу и убеждается, что ключ подошёл.
///
/// Без последней проверки неверный ключ проявился бы не здесь, а первым же
/// запросом — сообщением «file is not a database» посреди работы.
pub fn open_encrypted(path: &Path, key: &DbKey) -> Result<Connection> {
    let conn = Connection::open(path)?;
    conn.execute_batch(&format!("PRAGMA key = \"{}\";", key.pragma_literal()))?;
    // Любое чтение служебной таблицы расшифровывает первую страницу — этого
    // достаточно, чтобы отличить верный ключ от неверного.
    conn.query_row("SELECT count(*) FROM sqlite_master", [], |row| {
        row.get::<_, i64>(0)
    })?;
    Ok(conn)
}

/// Лежит ли по этому пути обычная, незашифрованная база SQLite.
///
/// Файла может не быть вовсе (первый запуск) — это не «незашифрованная база»,
/// мигрировать там нечего.
pub fn is_plaintext_database(path: &Path) -> bool {
    let Ok(bytes) = std::fs::read(path) else {
        return false;
    };
    bytes.len() >= SQLITE_HEADER.len() && &bytes[..SQLITE_HEADER.len()] == SQLITE_HEADER
}

/// Переводит существующую незашифрованную базу под шифрование.
///
/// Порядок шагов выбран так, чтобы в любой момент существовал хотя бы один
/// целый файл:
///
/// 1. `sqlcipher_export` пишет зашифрованную копию рядом, во временный файл;
/// 2. исходник переименовывается в `<имя>.plaintext.bak` — **не удаляется**;
/// 3. временный файл занимает место исходника.
///
/// Если что-то падает на шаге 1, исходник не тронут. Если на шаге 3 — исходник
/// лежит под `.bak`, и его достаточно переименовать обратно.
///
/// Старый файл остаётся на диске незашифрованным: удалить его — значит принять
/// за человека решение, после которого ошибка в ключе становится потерей всех
/// данных. Это его выбор, а не наш.
/// `trello_clone.db` → `trello_clone.db.plaintext-1787840000123.bak`, а если
/// такое имя занято — `…-1787840000123-1.bak` и так далее.
///
/// Возвращает именно **свободное** имя, а не просто сконструированное. Отказать
/// в миграции из-за занятого имени значило бы не запустить приложение ровно
/// тогда, когда человек восстанавливает данные, — а это та самая беда, от
/// которой уводит отметка времени. Перезаписывать чужую копию нельзя, но и
/// сдаваться при первом совпадении незачем: свободное имя всегда найдётся.
fn plaintext_backup_path(path: &Path) -> Option<std::path::PathBuf> {
    let stamp = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis())
        .unwrap_or(0);

    for attempt in 0..1000 {
        let suffix = if attempt == 0 {
            format!("{}{}.bak", BACKUP_PREFIX, stamp)
        } else {
            format!("{}{}-{}.bak", BACKUP_PREFIX, stamp, attempt)
        };
        let mut name = path.as_os_str().to_os_string();
        name.push(suffix);
        let candidate = std::path::PathBuf::from(name);
        if !candidate.exists() {
            return Some(candidate);
        }
    }
    None
}

pub fn encrypt_existing_database(path: &Path, key: &DbKey) -> std::result::Result<(), String> {
    let mut temp = path.as_os_str().to_os_string();
    temp.push(".encrypting");
    let temp = std::path::PathBuf::from(temp);

    // Остаток прерванной попытки помешал бы sqlcipher_export: он создаёт файл
    // сам и на существующий ругается.
    if temp.exists() {
        std::fs::remove_file(&temp)
            .map_err(|e| format!("Не удалось убрать остаток прошлой попытки: {}", e))?;
    }

    {
        let plain = Connection::open(path)
            .map_err(|e| format!("Не удалось открыть базу для шифрования: {}", e))?;

        // Путь подставляется параметром, ключ — текстом: параметр SQLCipher
        // принял бы за парольную фразу.
        plain
            .execute(
                &format!(
                    "ATTACH DATABASE ?1 AS encrypted KEY \"{}\"",
                    key.pragma_literal()
                ),
                rusqlite::params![temp.to_string_lossy()],
            )
            .map_err(|e| format!("Не удалось создать зашифрованный файл: {}", e))?;

        plain
            .query_row("SELECT sqlcipher_export('encrypted')", [], |_| Ok(()))
            .map_err(|e| format!("Не удалось перенести данные: {}", e))?;

        plain
            .execute_batch("DETACH DATABASE encrypted")
            .map_err(|e| format!("Не удалось закрыть зашифрованный файл: {}", e))?;
    }

    let backup = plaintext_backup_path(path).ok_or_else(|| {
        "Рядом уже лежит тысяча копий базы с такими именами. Уберите лишние — \
         перезаписывать копию ваших данных приложение не станет."
            .to_string()
    })?;

    std::fs::rename(path, &backup)
        .map_err(|e| format!("Не удалось отложить старую базу: {}", e))?;

    if let Err(e) = std::fs::rename(&temp, path) {
        // Вернуть как было — лучше незашифрованная работающая база, чем
        // отсутствие базы вообще.
        let _ = std::fs::rename(&backup, path);
        return Err(format!("Не удалось поставить зашифрованную базу на место: {}", e));
    }

    log::info!(
        "База зашифрована. Незашифрованный исходник сохранён как {:?}",
        backup
    );
    Ok(())
}

